"""Run the production N<=6 classical-subset build and atomically stow outputs."""
function build_knot_n6_classical_classification_db(; snapshot_path::AbstractString=N6CC_SNAPSHOT_PATH,
                                                     progress::Bool=true)
    started = time_ns()
    snapshot_sha, snapshot_bytes = _n6cc_sha256_file(snapshot_path)
    prepared = _n6cc_run_in_memory(N6CC_MAX_N;
        snapshot_path=snapshot_path, progress=progress, census=true)
    prepared.counts["canonical_state_total"] == 77989 || throw(ErrorException(
        "production classical state total is not 77989"))
    prepared.counts["all_gc_canonical_total"] == 3649221 || throw(ErrorException(
        "production all-GC canonical total is not 3649221"))
    prepared.counts["omitted_nonclassical_canonical_total"] == 3571232 ||
        throw(ErrorException("production omitted nonclassical total mismatch"))

    mkpath(dirname(N6CC_DB_OUTPUT))
    mkpath(dirname(N6CC_JSON_OUTPUT))
    mkpath(dirname(N6CC_MD_OUTPUT))
    tmp_db = tempname(dirname(N6CC_DB_OUTPUT)) * ".sqlite3"
    tmp_json = tempname(dirname(N6CC_JSON_OUTPUT)) * ".json"
    tmp_md = tempname(dirname(N6CC_MD_OUTPUT)) * ".md"
    try
        _n6cc_persist_db(tmp_db, prepared.classification, prepared.bridge,
                         prepared.labels, prepared.counts, prepared.census,
                         snapshot_sha)
        db_sha, db_bytes = _n6cc_sha256_file(tmp_db)
        elapsed = (time_ns() - started) / 1e9
        payload = _n6cc_payload(prepared, snapshot_sha, snapshot_bytes,
                                db_sha, db_bytes, elapsed)
        _n6cc_write_json(tmp_json, payload)
        _n6cc_write_markdown(tmp_md, payload)
        JSON.parsefile(tmp_json)
        mv(tmp_db, N6CC_DB_OUTPUT; force=true)
        mv(tmp_json, N6CC_JSON_OUTPUT; force=true)
        mv(tmp_md, N6CC_MD_OUTPUT; force=true)
        payload
    catch
        for path in (tmp_db, tmp_json, tmp_md)
            isfile(path) && rm(path)
        end
        rethrow()
    end
end

function _n6cc_parse_args(args)
    progress = true
    for arg in args
        arg == "--quiet" || throw(ArgumentError("unsupported argument $arg; use --quiet"))
        progress = false
    end
    progress
end

function main(args=ARGS)
    progress = _n6cc_parse_args(args)
    payload = build_knot_n6_classical_classification_db(; progress=progress)
    counts = payload["result"]["counts"]
    println("scope=classical canonical subset;max_n=6;barrier6=6;bridge_barrier=7")
    println("method_version=$(payload["method_version"]);method_released_at_utc=$(payload["method_released_at_utc"])")
    println("canonical_state_total=$(counts["canonical_state_total"]);planar_true=$(counts["planar_true"]);planar_false=$(counts["planar_false"])")
    println("classified=$(counts["classified"]);unresolved=$(counts["unresolved"]);transitions=$(counts["transitions"])")
    println("omitted_nonclassical_canonical_total=$(counts["omitted_nonclassical_canonical_total"])")
