"""Build the minimal classical-canonical N<=6 classification database.

The stored state set is the complete classical canonical subset generated by
`build_knot_n6_classification(6; barrier=6)`.  It is intentionally not the
full canonical Gauss-code census: nonclassical states are recorded only in
dataset-level counts and never as rows in this database.

The barrier-6 graph supplies its existing component labels.  The targeted
barrier-7 bridge is run only on barrier-6 unresolved components; a component
receives a bridge label only when the bridge connects it to exactly one known
label.  Otherwise its rows retain `knot_type=NULL` and
`classification_status='unresolved'`.
"""

