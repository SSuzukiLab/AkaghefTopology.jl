const N6CC_PROJECT_ROOT = joinpath(N6CC_REPO_ROOT, "threads", "PJ260830")
const N6CC_SNAPSHOT_PATH = joinpath(N6CC_PROJECT_ROOT, "data",
                                    "knotinfo-n6.json")
const N6CC_DB_OUTPUT = joinpath(N6CC_REPO_ROOT, "references", "items", "database",
                                "knotinfo", "knot-n6-classical-classification.sqlite3")
const N6CC_JSON_OUTPUT = joinpath(N6CC_PROJECT_ROOT, "data",
                                  "knot-n6-classical-classification.json")
const N6CC_MD_OUTPUT = joinpath(N6CC_PROJECT_ROOT, "reports",
                                "knot-n6-classical-classification.md")

const N6CC_METHOD_VERSION = "knot-n6-classical-classification-v1"
const N6CC_METHOD_RELEASED_AT_UTC = "2026-08-31T16:16:30Z"
const N6CC_MAX_N = 6
const N6CC_BARRIER6 = 6
const N6CC_BARRIER7 = 7

# Exact all-representation counts are kept as metadata because this fallback
# stores only the classical subset.  The n=6 value is the Burnside count for
# the repository's rotation-only canonicalization; the n<=5 prefix is the
# released exhaustive census.
const N6CC_ALL_CANONICAL_STATE_COUNTS = [1, 2, 14, 164, 3388, 96776, 3548876]
const N6CC_ALL_RAW_STATE_COUNTS = [1, 4, 48, 960, 26880, 967680, 42577920]

function _n6cc_sha256_file(path::AbstractString)
    bytes = read(path)
    bytes2hex(SHA.sha256(bytes)), length(bytes)
end

function _n6cc_sha256_lines(lines::Vector{String})
    context = SHA.SHA256_CTX()
    for line in lines
        SHA.update!(context, codeunits(string(line, '\n')))
    end
    bytes2hex(SHA.digest!(context))
end

function _n6cc_update!(context, line::AbstractString)
    SHA.update!(context, codeunits(string(line, '\n')))
    nothing
end

function _n6cc_raw_serialization(key::UInt64, n::Int)
    code, orientation = classical_gauss_key_to_code(key, n)
    "gauss=$(join(code, ','));orientation=$(join(orientation, ','))"
end

function _n6cc_state_serializations(classification::KnotN6Classification)
    result = [Set{String}() for _ in 0:classification.max_n]
    for diagram in classification.states
        n = crossing_count(diagram)
        push!(result[n + 1], canonical_serialization(diagram))
    end
    result
end

"""Recompute raw/canonical census fingerprints independently of the classifier."""
function _n6cc_classical_census_fingerprints(
        classification::KnotN6Classification)
    max_n = classification.max_n
    state_serializations = _n6cc_state_serializations(classification)
    raw_context = SHA.SHA256_CTX()
    canonical_context = SHA.SHA256_CTX()
    raw_counts = Int[]
    canonical_counts = Int[]

    for n in 0:max_n
        census = direct_classical_gauss_enumeration(n)
        raw_keys = sort!(collect(census.raw_keys))
        push!(raw_counts, length(raw_keys))
        length(raw_keys) == classification.raw_rooted_classical_counts_by_n[n + 1] ||
            throw(ErrorException("classical raw census disagrees at n=$n"))

        canonical = Set{String}()
        for key in raw_keys
            raw_line = "n=$(n)|raw|$(_n6cc_raw_serialization(key, n))"
            _n6cc_update!(raw_context, raw_line)
            diagram = classical_gauss_key_to_diagram(key, n)
            push!(canonical, canonical_serialization(diagram))
        end
        push!(canonical_counts, length(canonical))
        canonical == state_serializations[n + 1] ||
            throw(ErrorException("classical canonical census disagrees at n=$n"))
        length(canonical) == classification.state_counts[n + 1] ||
            throw(ErrorException("classical canonical count disagrees at n=$n"))
        for serialization in sort!(collect(canonical))
            _n6cc_update!(canonical_context, "n=$(n)|canonical|$(serialization)")
        end
    end

    (raw_fingerprint_sha256=bytes2hex(SHA.digest!(raw_context)),
     canonical_fingerprint_sha256=bytes2hex(SHA.digest!(canonical_context)),
     raw_counts=raw_counts,
     canonical_counts=canonical_counts)
end

function _n6cc_label_name(label::AbstractString)
    first(split(String(label), '^'; limit=2))
end

"""Merge barrier-6 labels with unambiguous barrier-7 bridge labels."""
function _n6cc_component_labels(classification::KnotN6Classification,
                                 bridge::KnotN6TargetedBridgeResult)
    labels = Dict{Int,String}(classification.component_type_labels)
    for component in bridge.seed_components
        connections = get(bridge.connected_known_labels, component, String[])
        length(connections) <= 1 || throw(ErrorException(
            "bridge component $component has multiple known labels"))
        if isempty(connections)
            haskey(bridge.resolved_components, component) && throw(ErrorException(
                "bridge marks component $component resolved without a connection"))
            continue
        end
        label = only(connections)
        get(bridge.resolved_components, component, nothing) == label ||
            throw(ErrorException("bridge resolution mismatch for component $component"))
        haskey(labels, component) && throw(ErrorException(
            "bridge unexpectedly relabels an existing barrier-6 component"))
        labels[component] = label
    end

    # The bridge performs the same check while joining its transient nodes;
    # repeat the name-level guard at the persistence boundary so a changed
    # bridge result cannot silently collapse distinct KnotInfo names.
    for component in keys(labels)
        label = labels[component]
        isempty(strip(_n6cc_label_name(label))) && throw(ErrorException(
            "empty knot name in component label"))
    end
    labels
end

function _n6cc_state_type_counts(classification::KnotN6Classification,
                                 labels::Dict{Int,String})
    counts = Dict{String,Int}()
    unresolved = 0
    for component in classification.components
        label = get(labels, component, nothing)
        if label === nothing
            unresolved += 1
        else
            counts[label] = get(counts, label, 0) + 1
        end
    end
    counts, unresolved
end

function _n6cc_classical_counts(classification::KnotN6Classification,
                                bridge::KnotN6TargetedBridgeResult,
                                labels::Dict{Int,String},
                                census)
    state_type_counts, unresolved_states =
        _n6cc_state_type_counts(classification, labels)
    total = length(classification.states)
    all_total = sum(N6CC_ALL_CANONICAL_STATE_COUNTS[1:classification.max_n + 1])
    all_raw_total = sum(N6CC_ALL_RAW_STATE_COUNTS[1:classification.max_n + 1])
    omitted = all_total - total
    omitted >= 0 || throw(ErrorException("negative omitted nonclassical population"))
    total == sum(classification.state_counts) || throw(ErrorException(
        "classical state total does not match per-n counts"))
    unresolved_states + sum(values(state_type_counts)) == total ||
        throw(ErrorException("classical status partition does not close"))
    census.raw_counts == classification.raw_rooted_classical_counts_by_n ||
        throw(ErrorException("raw census count vector mismatch"))
    census.canonical_counts == classification.state_counts ||
        throw(ErrorException("canonical census count vector mismatch"))

    Dict{String,Any}(
        "canonical_state_counts" => copy(classification.state_counts),
        "canonical_state_total" => total,
        "planar_true" => total,
        "planar_false" => 0,
        "classified" => total - unresolved_states,
        "unresolved" => unresolved_states,
        "nonclassical" => 0,
        "transitions" => 0,
        "component_count" => length(classification.component_roots),
        "barrier6_unresolved_component_count" =>
            length(classification.unresolved_components),
        "barrier7_resolved_component_count" =>
            length(bridge.resolved_components),
        "barrier7_unresolved_component_count" =>
            length(bridge.unresolved_components),
        "canonical_knot_type_counts" => state_type_counts,
        "raw_rooted_classical_counts" =>
            Dict(string(n) => census.raw_counts[n + 1] for n in 0:classification.max_n),
        "raw_rooted_classical_total" => sum(census.raw_counts),
        "raw_rooted_classical_unresolved_barrier6" =>
            classification.raw_rooted_classical_unresolved_count,
        "all_gc_canonical_state_counts" => copy(N6CC_ALL_CANONICAL_STATE_COUNTS),
        "all_gc_canonical_total" => all_total,
        "all_gc_raw_state_counts" => copy(N6CC_ALL_RAW_STATE_COUNTS),
        "all_gc_raw_total" => all_raw_total,
        "omitted_nonclassical_canonical_total" => omitted,
        "omitted_nonclassical_canonical_n6" =>
            N6CC_ALL_CANONICAL_STATE_COUNTS[classification.max_n + 1] -
            classification.state_counts[end],
        "omitted_nonclassical_raw_total" =>
            all_raw_total - sum(census.raw_counts),
        "known_label_count" => length(labels),
        "unresolved_components" => copy(bridge.unresolved_components))
end

function _n6cc_conventions()
    Dict{String,Any}(
        "scope" => "classical canonical subset; one-component diagrams; N<=6",
        "canonicalization" =>
            "KnotGaussDiagram v$(KNOT_GAUSS_CANON_VERSION); cyclic root shift + first-occurrence relabel only",
        "mirror_and_traversal_reversal" => "distinct",
        "strict_label_side" =>
            "+ is local KnotInfo PD representative; - is its mirror; no right/left-handed assertion",
        "classification" =>
            "barrier-6 graph labels plus targeted unresolved-component barrier-7 bridge",
        "nonclassical_rows" =>
            "omitted from this fallback DB; retained only in dataset-level all-GC counts",
        "persistence" =>
            "states and planar/knot_type/classification_status/method_version only; transitions, paths, certificates, Carter data, and per-state invariants are not stored")
end

function _n6cc_insert_rows!(store, classification::KnotN6Classification,
                            labels::Dict{Int,String}, counts::Dict{String,Any})
    method = N6CC_METHOD_VERSION
    MoveGraphStore._transaction(store.db) do
        for (index, diagram) in enumerate(classification.states)
            serialization = canonical_serialization(diagram)
            state = CanonicalState(serialization;
                area=AREA_2, representation="KnotGauss",
                complexity=Float64(crossing_count(diagram)))
            MoveGraphStore._dbexec(store.db, """
                INSERT INTO states(
                  state_id,state_hash,canonical_version,serialization,payload,
                  area,representation,complexity)
                VALUES (?,?,?,?,?,?,?,?)
            """, (state.state_id, state.state_hash, state.canonical_version,
                   state.serialization, nothing, state.area, state.representation,
                   state.complexity))
            component = classification.components[index]
            label = get(labels, component, nothing)
            status = label === nothing ? "unresolved" : "classified"
            MoveGraphStore._dbexec(store.db, """
                INSERT INTO state_classifications(
                  state_id,planar,knot_type,classification_status,method_version)
                VALUES (?,?,?,?,?)
            """, (state.state_id, 1, label, status, method))
        end
    end
    nothing
end

function _n6cc_query_count(db, sql::AbstractString)
    rows = MoveGraphStore._rows(db, sql)
    isempty(rows) && throw(ErrorException("count query returned no row"))
    Int(first(rows).n)
end

function _n6cc_verify_db(path::AbstractString,
                         expected::Dict{String,Any})
    store = open_store(path)
    try
        db = store.db
        _n6cc_query_count(db, "SELECT COUNT(*) AS n FROM states") ==
            expected["canonical_state_total"] || throw(ErrorException(
                "stored state count mismatch"))
        _n6cc_query_count(db, "SELECT COUNT(*) AS n FROM state_classifications") ==
            expected["canonical_state_total"] || throw(ErrorException(
                "stored classification count mismatch"))
        _n6cc_query_count(db, "SELECT SUM(planar=1) AS n FROM state_classifications") ==
            expected["planar_true"] || throw(ErrorException("stored planar count mismatch"))
        _n6cc_query_count(db, "SELECT SUM(planar=0) AS n FROM state_classifications") == 0 ||
            throw(ErrorException("stored nonclassical row found"))
        _n6cc_query_count(db, "SELECT COUNT(*) AS n FROM transitions") == 0 ||
            throw(ErrorException("stored transition found"))
        _n6cc_query_count(db, "SELECT COUNT(*) AS n FROM certificate_paths") == 0 ||
            throw(ErrorException("stored certificate path found"))
        _n6cc_query_count(db, "SELECT COUNT(*) AS n FROM invariants") == 0 ||
            throw(ErrorException("stored invariant found"))
        _n6cc_query_count(db, "SELECT COUNT(*) AS n FROM states WHERE payload IS NOT NULL") == 0 ||
            throw(ErrorException("stored state payload found"))
        columns = String.(getproperty.(MoveGraphStore._rows(
            db, "PRAGMA table_info(state_classifications)"), :name))
        columns == ["state_id", "planar", "knot_type", "classification_status",
                    "method_version"] || throw(ErrorException(
            "unexpected classification columns"))
        api_counts = classification_counts(store, N6CC_METHOD_VERSION)
        api_counts["total"] == expected["canonical_state_total"] ||
            throw(ErrorException("classification API total mismatch"))
        api_counts["planar_true"] == expected["planar_true"] ||
            throw(ErrorException("classification API planar count mismatch"))
        api_counts["planar_false"] == 0 ||
            throw(ErrorException("classification API nonclassical count mismatch"))
        api_counts["classified"] == expected["classified"] ||
            throw(ErrorException("classification API classified count mismatch"))
        api_counts["unresolved"] == expected["unresolved"] ||
            throw(ErrorException("classification API unresolved count mismatch"))
        api_counts["nonclassical"] == 0 ||
            throw(ErrorException("classification API nonclassical status mismatch"))
        api_counts["knot_type_counts"] == expected["canonical_knot_type_counts"] ||
            throw(ErrorException("classification API type counts mismatch"))
        true
    finally
        close_store!(store)
    end
end

function _n6cc_persist_db(path::AbstractString,
                          classification::KnotN6Classification,
                          bridge::KnotN6TargetedBridgeResult,
                          labels::Dict{Int,String},
                          counts::Dict{String,Any},
                          census,
                          snapshot_sha::AbstractString)
    store = open_store(path)
    try
        run_counts = copy(counts)
        run_counts["census_raw_fingerprint_sha256"] = census.raw_fingerprint_sha256
        run_counts["census_canonical_fingerprint_sha256"] =
            census.canonical_fingerprint_sha256
        run_counts["barrier6_graph_fingerprint_sha256"] = classification.fingerprint
        run_counts["barrier7_bridge_fingerprint_sha256"] = bridge.fingerprint
        run_counts["knotinfo_snapshot_sha256"] = snapshot_sha
        register_classification_run!(store; method_version=N6CC_METHOD_VERSION,
            canonical_version=KNOT_GAUSS_CANON_VERSION,
            max_n=classification.max_n,
            barrier=N6CC_BARRIER7,
            census_fingerprint=census.canonical_fingerprint_sha256,
            classification_fingerprint=bridge.fingerprint,
            counts=run_counts, conventions=_n6cc_conventions(),
            created_at_utc=N6CC_METHOD_RELEASED_AT_UTC)
        _n6cc_insert_rows!(store, classification, labels, counts)
    finally
        close_store!(store)
    end
    _n6cc_verify_db(path, counts)
    nothing
end

function _n6cc_run_in_memory(max_n::Integer;
                             snapshot_path::AbstractString=N6CC_SNAPSHOT_PATH,
                             progress::Bool=false,
                             census::Bool=true)
    max_n = Int(max_n)
    0 <= max_n <= N6CC_MAX_N || throw(ArgumentError("max_n must lie in 0:6"))
    classification = build_knot_n6_classification(max_n; barrier=max_n,
        snapshot_path=snapshot_path, progress=progress)
    bridge = run_knot_n6_targeted_bridge(classification;
        barrier=N6CC_BARRIER7, progress=progress)
    labels = _n6cc_component_labels(classification, bridge)
    census_result = census ? _n6cc_classical_census_fingerprints(classification) :
        (raw_fingerprint_sha256="fixture-raw-census",
         canonical_fingerprint_sha256="fixture-canonical-census",
         raw_counts=copy(classification.raw_rooted_classical_counts_by_n),
         canonical_counts=copy(classification.state_counts))
    counts = _n6cc_classical_counts(classification, bridge, labels, census_result)
    (classification=classification, bridge=bridge, labels=labels,
     census=census_result, counts=counts)
end

function _n6cc_payload(prepared, snapshot_sha::AbstractString,
                       snapshot_bytes::Integer, db_sha::AbstractString,
                       db_bytes::Integer, elapsed_seconds::Real)
    classification = prepared.classification
    bridge = prepared.bridge
    census = prepared.census
    counts = prepared.counts
    Dict{String,Any}(
        "schema_version" => 2,
        "method_version" => N6CC_METHOD_VERSION,
        "method_released_at_utc" => N6CC_METHOD_RELEASED_AT_UTC,
        "scope" => "classical canonical subset",
        "runtime" => Dict{String,Any}(
            "julia_version" => string(VERSION),
            "command" => "julia --startup-file=no --pkgimages=no --project=. scripts/build_knot_n6_classical_classification_db.jl",
            "os" => string(Sys.KERNEL),
            "machine" => string(Sys.MACHINE),
            "elapsed_seconds" => elapsed_seconds),
        "input" => Dict{String,Any}(
            "snapshot" => "threads/PJ260830/data/knotinfo-n6.json",
            "snapshot_sha256" => snapshot_sha,
            "snapshot_bytes" => snapshot_bytes,
            "classical_census_raw_fingerprint_sha256" => census.raw_fingerprint_sha256,
            "classical_census_canonical_fingerprint_sha256" =>
                census.canonical_fingerprint_sha256,
            "barrier6_graph_fingerprint_sha256" => classification.fingerprint,
            "barrier7_bridge_fingerprint_sha256" => bridge.fingerprint),
        "method" => Dict{String,Any}(
            "classification_version" => KNOT_N6_CLASSIFICATION_VERSION,
            "enumeration_version" => CLASSICAL_GAUSS_ENUMERATION_VERSION,
            "bridge_version" => KNOT_N6_TARGETED_BRIDGE_VERSION,
            "barrier6" => N6CC_BARRIER6,
            "barrier7" => N6CC_BARRIER7,
            "conventions" => _n6cc_conventions()),
        "result" => Dict{String,Any}(
            "counts" => counts,
            "component_labels" => Dict(string(component) => label
                                        for (component, label) in
                                        sort!(collect(prepared.labels))),
            "barrier6_unresolved_components" =>
                copy(classification.unresolved_components),
            "barrier7_summary" => knot_n6_targeted_bridge_summary(bridge)),
        "database" => Dict{String,Any}(
            "path" => "references/items/database/knotinfo/knot-n6-classical-classification.sqlite3",
            "sha256" => db_sha,
            "bytes" => db_bytes))
end

function _n6cc_write_json(path::AbstractString, payload)
    open(path, "w") do io
        JSON.print(io, payload)
        write(io, '\n')
    end
end

