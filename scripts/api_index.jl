function modules(root)
    result = Module[]
    function visit(m)
        m in result && return
        push!(result, m)
        for n in names(m; all=true, imported=false)
            isdefined(m, n) || continue
            v = getfield(m, n)
            v isa Module && v !== m && parentmodule(v) === m && visit(v)
        end
    end
    visit(root)
    sort!(result; by=modname)
end

"Resolve registered names using bindings, never by evaluating source text."
function resolve_name(root, name; context=root)
    parts = split(name, '.')
    start = first(parts) == string(nameof(root)) ? root : context
    first(parts) == string(nameof(root)) && popfirst!(parts)
    for part in parts
        start isa Module && isdefined(start, Symbol(part)) || return nothing
        start = getfield(start, Symbol(part))
    end
    start
end

function registry(root, gaps, file=joinpath(ROOT, "docs", "objects.toml"))
    reg = TOML.parsefile(file)
    haskey(reg, "unassigned") && error("unassigned is reserved by §4.7")
    types = Dict{String,Vector{Any}}()
    for key in sort!(collect(keys(reg)))
        occursin(r"^[a-zA-Z0-9_-]+$", key) || error("Unsafe object directory: $key")
        item = reg[key]
        types[key] = Any[]
        for name in item["types"]
            v = resolve_name(root, name)
            if !(v isa Type)
                push!(gaps, "Registry type `$name` cannot be resolved to a type.")
            else
                push!(types[key], v)
            end
        end
        for field in ("specs", "conventions"), target in item[field]
            isfile(joinpath(ROOT, first(split(target, '#')))) ||
                push!(gaps, "Registry link `$target` in `$key` does not exist.")
        end
    end
    reg, types
end

"Expand registry source paths once; ambiguous files remain unassigned."
function source_registry(reg, gaps)
    owners = Dict{String,String}()
    conflicts = Set{String}()
    for key in sort!(collect(keys(reg))), source in get(reg[key], "sources", String[])
        path = normpath(joinpath(ROOT, source))
        relative = slash(relpath(path, ROOT))
        if isabspath(source) || relative == ".." || startswith(relative, "../")
            push!(gaps, "Registry source `$source` in `$key` is not library-relative.")
            continue
        end
        files = String[]
        if isdir(path)
            for (dir, _, names) in walkdir(path), name in names
                endswith(name, ".jl") && push!(files, joinpath(dir, name))
            end
        elseif isfile(path)
            push!(files, path)
        else
            push!(gaps, "Registry source `$source` in `$key` does not exist.")
        end
        for file in sort!(files)
            previous = get(owners, file, key)
            if previous != key
                push!(conflicts, file)
                push!(gaps, "Registry source `$(slash(relpath(file, ROOT)))` belongs to both `$previous` and `$key`.")
            else
                owners[file] = key
            end
        end
    end
    for file in conflicts
        delete!(owners, file)
    end
    owners
end

"Apply source ownership only when no method has a registered argument or return."
function assign_sources!(rows, owners)
    any(r -> !isempty(r.objects), rows) && return
    for i in eachindex(rows)
        r = rows[i]
        r.method === nothing && continue # §4.7 declarations have no defining method.
        file = source_file(String(r.method.file))
        file === nothing && continue
        owner = get(owners, file, nothing)
        owner === nothing && continue
        rows[i] = merge(r, (objects=[owner], preferred=[owner]))
    end
end

"Type membership, including containers, Union arms and non-Any supertypes."
#
# Both arguments are types. Without `@nospecialize` Julia compiles this
# function, and every closure that captures `t`, once per pair of types:
# measured 14.6 s for 56 methods, so the 985 methods of the library never
# finished within 10 minutes (lead, 2026-11-25). Keep the loops explicit.
function mentions(@nospecialize(t), @nospecialize(registered), ancestors::Bool=true)
    t === Any && return false
    t === Union{} && return false
    t isa TypeVar && return t.ub !== Any && mentions(t.ub, registered, ancestors)
    if t isa Union
        for x in Base.uniontypes(t)
            mentions(x, registered, ancestors) && return true
        end
        return false
    end
    if Base.isvarargtype(t)
        return mentions(t.T, registered, ancestors)
    end
    t isa Type || return false
    (t <: registered || (ancestors && registered <: t)) && return true
    body = Base.unwrap_unionall(t)
    body isa DataType || return false
    for x in body.parameters
        mentions(x, registered, ancestors) && return true
    end
    false
end

function objects_for(@nospecialize(t), types; ancestors::Bool=true)
    found = String[]
    for (key, vals) in types
        for v in vals
            if mentions(t, v, ancestors)
                push!(found, key)
                break
            end
        end
    end
    sort!(found)
end

function documents(v, mods)
    result = NamedTuple[]
    seen = Base.IdSet{Any}()
    for m in unique(vcat(mods, [parentmodule(v)]))
        meta = Base.Docs.meta(m; autoinit=false)
        meta === nothing && continue
        for (binding, multi) in meta
            binding isa Base.Docs.Binding || continue
            Base.Docs.defined(binding) || continue
            Base.Docs.resolve(binding) === v || continue
            multi isa Base.Docs.MultiDoc || continue
            for sig in multi.order
                d = multi.docs[sig]
                d in seen && continue
                push!(seen, d)
                raw = isempty(d.text) ? "" : sprint(io -> foreach(x -> print(io, x), d.text))
                push!(result, (sig=sig, doc=d, raw=replace(raw, "\r\n" => "\n"),
                    context=get(d.data, :module, m)))
            end
        end
    end
    sort!(result; by=d -> (string(d.sig), d.raw))
end

function choose_doc(method, docs)
    isempty(docs) && return nothing
    sig = Base.tuple_type_tail(method.sig)
    exact = filter(d -> d.sig == sig, docs)
    !isempty(exact) && return first(exact)
    applicable = filter(d -> d.sig !== Union{} && sig <: d.sig, docs)
    !isempty(applicable) && return first(sort!(applicable; by=d ->
        (count(e -> e.sig !== Union{} && e.sig <: d.sig, docs), string(d.sig))))
    generic = filter(d -> d.sig === Union{}, docs)
    isempty(generic) ? nothing : first(generic)
end

function reflected_signature(m)
    tv, decls, _, _ = Base.arg_decl_parts(m)
    io = IOBuffer()
    print(io, decls[1][2], '(')
    for (i, (name, typ)) in enumerate(decls[2:end])
        i > 1 && print(io, ", ")
        print(io, name)
        isempty(typ) || print(io, "::", typ)
    end
    kws = Base.kwarg_decl(m)
    isempty(kws) || print(io, "; ", join(string.(kws), ", "))
    print(io, ')')
    Base.show_method_params(io, tv)
    replace(String(take!(io)), r"\bMain\." => "")
end

function first_sentence(text)
    text = oneline(text)
    found = match(r"^.*?[.!?](?=\s|$)"s, text)
    found === nothing ? text : found.match
end

"Read the final evidence bracket, retaining nested wikilink brackets."
function evidence_annotation(text)
    text = strip(text)
    isempty(text) && return ("", "")
    last(text) == ']' || return ("", "")
    depth = 0
    i = lastindex(text)
    while i >= firstindex(text)
        text[i] == ']' && (depth += 1)
        if text[i] == '['
            depth -= 1
            if depth == 0
                annotation = String(strip(text[nextind(text, i):prevind(text, lastindex(text))]))
                parts = split(annotation, ':'; limit=2)
                status = String(strip(first(parts)))
                supported = length(parts) == 2 && !isempty(strip(parts[2]))
                return status in GUARANTEE_STATUSES && supported ? (status, annotation) : ("", annotation)
            end
        end
        i = prevind(text, i)
    end
    ("", "")
end

"Numbered top-level items of the Guarantees section, using Julia's Markdown AST."
function guarantees(md, sections=contract_sections(md))
    result = Guarantee[]
    for block in sections["Guarantees"]
        if block isa Markdown.List && block.ordered >= 0
            for (offset, item) in enumerate(block.items)
                # A nested subcondition or a code example cannot supply its
                # parent's status; the annotation belongs to the final paragraph.
                text = !isempty(item) && last(item) isa Markdown.Paragraph ?
                    oneline(sprint(show, MIME"text/markdown"(), Markdown.MD([last(item)]))) : ""
                status, annotation = evidence_annotation(text)
                push!(result, (number=block.ordered + offset - 1, status=status, annotation=annotation))
            end
        end
    end
    result
end

"Mandatory section bodies, including subsections but excluding neighbouring sections."
function contract_sections(md)
    sections = Dict(h => Any[] for h in REQUIRED)
    active = ""
    level = 0
    for b in md.content
        if b isa Markdown.Header
            heading = replace(oneline(sprint(show, MIME"text/markdown"(), Markdown.MD([b]))), r"^#+\s*" => "")
            depth = typeof(b).parameters[1]
            if heading in REQUIRED
                active, level = heading, depth
            elseif depth <= level
                active = ""
            end
        elseif !isempty(active)
            push!(sections[active], b)
        end
    end
    sections
end

function section_nonempty(@nospecialize(node))
    if node isa AbstractString
        # Julia Markdown smart punctuation can turn -- into an en dash.
        text = replace(node, r"<!(?:--|–).*?(?:--|–)>"s => "", r"(?m)^Role:\s*\w+\s*$" => "")
        return !isempty(strip(text))
    elseif node isa Markdown.Header
        return false
    elseif node isa Markdown.Code
        return !isempty(strip(node.code))
    elseif node isa Markdown.Paragraph
        # Comments may be split into several smart-punctuation text fragments.
        all(x -> x isa AbstractString, node.content) && return section_nonempty(join(node.content))
        return section_nonempty(node.content)
    elseif node isa AbstractVector
        for child in node
            section_nonempty(child) && return true
        end
        return false
    elseif node isa Markdown.LaTeX
        return !isempty(strip(node.formula))
    elseif node isa Markdown.Image
        return !isempty(strip(node.url))
    end
    for field in (:content, :text, :items, :rows)
        hasproperty(node, field) && return section_nonempty(getproperty(node, field))
    end
    false
end

"Inspect the Markdown AST; source files are not parsed for contracts."
function contract(d, fallback; constructor=false, extension=false)
    d === nothing && return (signature=fallback * " -> ?", summary="", missing=String[],
        status="no contract", role=constructor ? "construct" : "other", returns="", guarantees=Guarantee[], links=String[])
    md = Markdown.parse(d.raw)
    blocks = md.content
    sig = ""
    ret = ""
    signature_block = ""
    multiple_signatures = false
    if !isempty(blocks) && first(blocks) isa Markdown.Code
        code = strip(first(blocks).code)
        if occursin('(', code) && !occursin("julia>", code)
            signature_block = oneline(code)
            multiple_signatures = count(line -> occursin(r"^\s*[\p{L}_][\p{L}\p{N}_.!]*\s*\(", line), split(code, '\n')) > 1
            if !multiple_signatures
                sig = signature_block
                found = match(r"\s+->\s+(.+)$", sig)
                found === nothing || (ret = strip(found.captures[1]))
            end
        end
    end
    # Preserve the paragraph's source spelling (including inline Markdown).
    paragraphs = split(strip(d.raw), r"\n\s*\n")
    summary = ""
    for p in paragraphs
        startswith(p, "    ") && continue
        s = strip(p)
        (startswith(s, "#") || startswith(s, "```") || startswith(s, "Role:")) && continue
        !isempty(signature_block) && oneline(s) == signature_block && continue
        summary = first_sentence(s)
        break
    end
    sections = contract_sections(md)
    examples = any(sections["Examples"]) do b
        b isa Markdown.Code || return false
        isempty(strip(b.code)) && return false
        extension ? b.language == "julia" && occursin(r"^\s*using\s+", b.code) :
            startswith(b.language, "jldoctest")
    end
    missing = String[]
    isempty(sig) && push!(missing, "signature")
    multiple_signatures && push!(missing, "one signature per method")
    isempty(ret) && push!(missing, "return type")
    isempty(summary) && push!(missing, "summary")
    for h in REQUIRED
        section_nonempty(sections[h]) || push!(missing, h)
    end
    !isempty(sections["Examples"]) && !examples && push!(missing, extension ? "extension example (julia, starting with using)" : "jldoctest")
    rolematch = match(r"(?:^|\n)Role:\s*(\w+)\s*$", strip(d.raw))
    role = rolematch === nothing ? (constructor ? "construct" : "other") : rolematch.captures[1]
    (rolematch === nothing || !(role in ROLES)) && push!(missing, "Role")
    role in ROLES || (role = "other")
    evidence = guarantees(md, sections)
    any(g -> isempty(g.status), evidence) && push!(missing, "Guarantee status")
    display = isempty(sig) ? fallback : sig
    isempty(ret) && (display *= " -> ?")
    (signature=display, summary=summary, missing=missing,
        status=isempty(missing) ? "complete" : "incomplete", role=role, returns=ret,
        guarantees=evidence, links=markdown_links(md))
end

"Types in a declaration's documented positional signature; no optional package is loaded."
function signature_arguments(root, signature, context)
    text = first(split(signature, r"\s+->\s+"; limit=2))
    ex = Meta.parse(text; raise=false)
    while ex isa Expr && ex.head in (:where, :(::))
        ex = ex.args[1]
    end
    ex isa Expr && ex.head == :call || return Any[]
    result = Any[]
    for arg in ex.args[2:end]
        arg isa Expr && arg.head == :parameters && continue
        while arg isa Expr && arg.head in (:kw, :(=), :(...))
            arg = arg.args[1]
        end
        t = arg isa Expr && arg.head == :(::) ? return_type(root, string(last(arg.args)), context) : nothing
        push!(result, t === nothing ? Any : t)
    end
    result
end

"Loaded methods physically defined beneath this library's ext directory."
function extension_method(method::Method)
    file = String(method.file)
    path = normpath(isabspath(file) ? file : joinpath(ROOT, file))
    relative = slash(relpath(path, joinpath(ROOT, "ext")))
    relative != ".." && !startswith(relative, "../") && !isabspath(relative)
end

# Resolve only type expressions in docstring signature lines. No eval, calls,
# compiler inference, or source-code parsing is involved.
function return_type(root, text, context)
    isempty(text) && return nothing
    ex = Meta.parse(text; raise=false)
    function resolve(ex)
        if ex isa Symbol
            v = resolve_name(root, string(ex); context)
            v === nothing && (v = resolve_name(root, string(ex)))
            v === nothing && isdefined(Core, ex) && (v = getfield(Core, ex))
            v === nothing && isdefined(Base, ex) && (v = getfield(Base, ex))
            return v
        elseif ex isa Expr && ex.head == :.
            return resolve_name(root, string(ex); context)
        elseif ex isa Expr && ex.head == :curly
            base = resolve(ex.args[1])
            args = map(resolve, ex.args[2:end])
            (base === nothing || any(isnothing, args)) && return nothing
            try
                return Core.apply_type(base, args...)
            catch
                return nothing
            end
        elseif ex isa Integer
            return ex
        end
        nothing
    end
    result = resolve(ex)
    result isa Type ? result : nothing
end

function source_file(path)
    s = string(path)
    s in ("", "none") && return nothing
    candidates = isabspath(s) ? [s] : [joinpath(ROOT, s), joinpath(ROOT, "src", s)]
    for p in candidates
        if isfile(p)
            relative = slash(relpath(normpath(p), normpath(joinpath(ROOT, "..", ".."))))
            (relative == ".." || startswith(relative, "../")) && continue
            return normpath(p)
        end
    end
    nothing
end

function external_location(method)
    m = method.module
    while parentmodule(m) !== m && parentmodule(m) !== Main
        m = parentmodule(m)
    end
    string(nameof(m)) * "/" * last(split(slash(method.file), '/')) * ":" * string(method.line)
end

cf_lines(raw) = [strip(m.match) for m in eachmatch(r"(?m)^\s*cf:\s*[^\n]+", raw)]

"The only source scan: cf: lines in the initial file comment/docstring header."
function file_sources(path)
    path === nothing && return String[]
    result = String[]
    pending_doc = String[]
    in_doc = false
    in_block = false
    for line in eachline(path)
        s = strip(line)
        if in_doc
            append!(pending_doc, cf_lines(s))
            occursin("\"\"\"", s) && (in_doc = false)
            continue
        elseif in_block
            append!(result, cf_lines(replace(s, r"^#\s?" => "")))
            occursin("=#", s) && (in_block = false)
            continue
        elseif isempty(s)
            continue
        elseif startswith(s, "#=")
            in_block = !occursin("=#", s)
            append!(result, cf_lines(s[3:end]))
        elseif startswith(s, '#')
            append!(result, cf_lines(replace(s, r"^#\s?" => "")))
        elseif startswith(s, "\"\"\"")
            rest = s[4:end]
            in_doc = !occursin("\"\"\"", rest)
            append!(pending_doc, cf_lines(rest))
        elseif startswith(s, "module ") || startswith(s, "baremodule ")
            # Only a module docstring is a file header. The first callable's
            # docstring belongs to that callable, even when it starts the file.
            append!(result, pending_doc)
            empty!(pending_doc)
            continue
        else
            break
        end
    end
    unique(result)
end

function filename(name)
    io = IOBuffer()
    for c in name
        if c in ('<', '>', ':', '"', '/', '\\', '|', '?', '*') || Int(c) < 32
            for b in codeunits(string(c))
                print(io, '%', uppercase(string(b; base=16, pad=2)))
            end
        else
            print(io, c)
        end
    end
    String(take!(io)) * ".md"
end

link(from, to) = replace(slash(relpath(to, dirname(from))), "%" => "%25", " " => "%20", "#" => "%23")
code(s) = "`" * replace(oneline(s), '`' => '\'') * "`"

"Shorten a documented/reflected signature with Julia's parser, never source scanning."
function short_signature(signature, fallback=signature)
    parts = split(signature, r"\s+->\s+"; limit=2)
    ret = length(parts) == 2 ? parts[2] : "?"
    ex = Meta.parse(first(parts); raise=false)
    while ex isa Expr && ex.head in (:where, :(::))
        ex = first(ex.args)
    end
    if !(ex isa Expr && ex.head == :call)
        if fallback != signature
            return short_signature(first(split(fallback, r"\s+->\s+"; limit=2)) * " -> " * ret)
        end
        # A prose signature can be invalid Julia. Keep its callable name; full
        # text remains in the contract, rather than leaking it into an index.
        return first(split(first(parts), '('; limit=2)) * "(...) -> " * short_type(ret)
    end
    args = String[]
    keywords = false
    positional = 0
    for arg in ex.args[2:end]
        if arg isa Expr && arg.head == :parameters
            keywords = true
            continue
        end
        positional += 1
        positional <= 4 && push!(args, short_argument(arg))
    end
    positional > 4 && push!(args, "…")
    short_type(sprint(Base.show_unquoted, first(ex.args))) * "(" * join(args, ", ") *
        (keywords ? "; …" : "") * ") -> " * short_type(ret)
end

function short_argument(arg)
    if arg isa Expr
        if arg.head == :kw
            return short_argument(arg.args[1]) * " = " * oneline(sprint(Base.show_unquoted, arg.args[2]))
        elseif arg.head == :(::)
            name = length(arg.args) == 2 ? short_argument(first(arg.args)) : ""
            return name * "::" * short_type(sprint(Base.show_unquoted, last(arg.args)))
        elseif arg.head == :...
            return short_argument(first(arg.args)) * "..."
        end
    end
    oneline(sprint(Base.show_unquoted, arg))
end

# Display-only qualification removal; type resolution still uses the full text.
short_type(s) = replace(oneline(s), r"(?:\b[\p{L}_][\p{L}\p{N}_]*\.)+([\p{L}_][\p{L}\p{N}_]*)" => s"\1")

function indexline(row, from)
    status = row.contract.status
    suffix = !isempty(row.external_package) ? " [external: " * row.external_package * "]" :
        status == "complete" ? "" : status == "no contract" ? " [no contract]" :
        " [incomplete]"
    "- " * code(row.short_signature) * " — " * row.contract.summary * suffix *
        " [contract](" * link(from, row.path) * ")"
end

rowkey(row) = (row.label, row.contract.signature, row.doc === nothing ? "" : row.doc.raw)

"Different contracts for one full documented signature need a precedence rule."
function contract_conflicts(rows)
    seen = Dict{String,String}()
    conflicts = String[]
    for r in rows
        r.doc === nothing && continue
        signature, raw = r.contract.signature, r.doc.raw
        if haskey(seen, signature) && seen[signature] != raw
            push!(conflicts, signature)
        else
            seen[signature] = raw
        end
    end
    sort!(unique!(conflicts))
end

function render_doc(raw, from, paths, gaps, label; external=false)
    # @ref targets become ordinary links. Relative links in contract docstrings
    # use the spec's docs-relative template (../specs, ../conventions).
    raw = replace(raw, r"\[([^\]]+)\]\(@ref(?:\s+([^\)]+))?\)" => function(s)
        m = match(r"\[([^\]]+)\]\(@ref(?:\s+([^\)]+))?\)", s)
        target = strip(m.captures[2] === nothing ? replace(m.captures[1], "`" => "") : m.captures[2])
        choices = get(paths, target, String[])
        if length(choices) == 1
            return "[" * m.captures[1] * "](" * link(from, only(choices)) * ")"
        end
        push!(gaps, "$label: unresolved or ambiguous docstring reference `$target`.")
        external ? code(replace(m.captures[1], r"^`(.*)`$"s => s"\1")) : s
    end)
    replace(raw, r"\]\(([^\)\s]+)([^\)]*)\)" => s -> begin
        m = match(r"\]\(([^\)\s]+)([^\)]*)\)", s)
        target = spec_target(m.captures[1])
        target === nothing ? s : "](" * spec_link(from, target) * m.captures[2] * ")"
    end)
end

function generate(root; output=OUT, registry_file=joinpath(ROOT, "docs", "objects.toml"), spec_pages=nothing)
    out = normpath(output)
    (out == OUT || (dirname(out) == joinpath(ROOT, "scripts") && startswith(basename(out), ".api-check-"))) ||
        error("Output must be docs/api or a generator diagnostic directory beside this script")
    gaps = String[]
    mods = modules(root)
    reg, types = registry(root, gaps, registry_file)
    sourceowners = source_registry(reg, gaps)
    exports = IdDict{Any,Vector{String}}()
    omitted = String[]
    for m in mods, n in sort!(names(m); by=string)
        label = modname(m) * "." * string(n)
        if !isdefined(m, n)
            push!(gaps, "$label: exported binding is undefined.")
            continue
        end
        v = getfield(m, n)
        if startswith(string(n), "@")
            push!(omitted, "$label (macro)")
        elseif v isa Module
            push!(omitted, "$label (module; its own exports are traversed)")
        elseif v isa Function || v isa Type
            # Only explicitly exported bindings reach this branch. Merely adding
            # a method to Base.show etc. does not make that binding an export.
            push!(get!(exports, v, String[]), label)
        else
            push!(omitted, "$label (constant)")
        end
    end
    allvalues = sort!(collect(keys(exports)); by=qualified)
    doccache = IdDict(v => documents(v, mods) for v in allvalues)
    unregistered = String[]
    entries = NamedTuple[]
    for v in allvalues
        istype = v isa Type
        label = qualified(v)
        external_package = parentmodule(v) in mods ? "" : package_name(parentmodule(v))
        owner = istype ? objects_for(v, types; ancestors=false) : String[]
        istype && length(owner) != 1 && push!(unregistered, "$label ($(length(owner)) objects)")
        ds = doccache[v]
        ms = collect(methods(v))
        istype || !isempty(external_package) || filter!(m -> m.module in mods || extension_method(m), ms)
        sort!(ms; by=m -> (reflected_signature(m), slash(m.file), m.line))
        extension = !istype && isempty(external_package) && (isempty(ms) || any(extension_method, ms))
        rows = NamedTuple[]
        useddocs = Base.IdSet{Any}()
        for method in ms
            d = choose_doc(method, ds)
            c = contract(d, reflected_signature(method); constructor=istype, extension)
            args = collect(Base.unwrap_unionall(method.sig).parameters[2:end])
            groups = [objects_for(t, types) for t in args]
            rtype = d === nothing ? nothing : return_type(root, c.returns, d.context)
            # A declaration cannot import the optional package merely to name its
            # return type. A loaded extension may resolve it in its own bindings.
            rtype === nothing && d !== nothing && extension_method(method) &&
                (rtype = return_type(root, c.returns, method.module))
            returns = rtype === nothing ? String[] : objects_for(rtype, types; ancestors=false)
            isempty(external_package) && !isempty(c.returns) && rtype === nothing && push!(gaps,
                "$label: return type `$(c.returns)` could not be resolved from the docstring.")
            belonging = sort!(unique(vcat(groups..., returns, istype ? owner : String[])))
            preferred = istype ? owner : begin
                firstmatch = findfirst(!isempty, groups)
                firstmatch === nothing ? returns : groups[firstmatch]
            end
            d === nothing || push!(useddocs, d.doc)
            push!(rows, (contract=c, doc=d, method=method, objects=belonging,
                preferred=preferred, args=args))
        end
        # Abstract types and generic declarations can have docs without methods.
        for d in ds
            d.doc in useddocs && continue
            c = contract(d, string(nameof(v)) * "(...)"; constructor=istype, extension)
            rt = return_type(root, c.returns, d.context)
            args = !istype && isempty(ms) ? signature_arguments(root, c.signature, d.context) : Any[]
            groups = [objects_for(t, types) for t in args]
            returns = rt === nothing ? String[] : objects_for(rt, types; ancestors=false)
            belonging = istype ? owner : sort!(unique(vcat(groups..., returns)))
            firstmatch = findfirst(!isempty, groups)
            preferred = istype ? owner : firstmatch === nothing ? returns : groups[firstmatch]
            # §4.7 retains the synthetic row for unloaded declarations, but
            # their documented signature now decides membership and type scope.
            if !istype && isempty(ms)
                c = merge(c, (signature=string(nameof(v)) * "(...) -> " * (isempty(c.returns) ? "?" : c.returns),))
            end
            push!(rows, (contract=c, doc=d, method=nothing, objects=belonging,
                preferred=preferred, args=args))
        end
        if isempty(rows)
            c = contract(nothing, string(nameof(v)) * "(...)"; constructor=istype)
            push!(rows, (contract=c, doc=nothing, method=nothing, objects=owner,
                preferred=owner, args=Any[]))
        end
        if !isempty(external_package)
            for i in eachindex(rows)
                rows[i] = merge(rows[i], (contract=merge(rows[i].contract,
                    (status="external", missing=String[])),))
            end
        end
        istype || assign_sources!(rows, sourceowners)
        # Count real methods BEFORE collapsing optional-argument doc rows.
        # §4.3 also breaks an individual type's membership tie by directory name.
        votes = Dict{String,Int}()
        for r in rows
            !isempty(ms) && r.method === nothing && continue
            key = isempty(r.preferred) ? "unassigned" : first(r.preferred)
            votes[key] = get(votes, key, 0) + 1
        end
        location = first(sort!(collect(keys(votes)); by=k -> (-votes[k], k)))
        belonging = sort!(unique(vcat([r.objects for r in rows]...)))
        isempty(belonging) && (belonging = ["unassigned"])
        any(r -> isempty(r.objects), rows) && push!(belonging, "unassigned")
        sort!(unique!(belonging))
        # Optional arguments represented by one documented signature get one row.
        # Retain all object memberships when those methods collapse together.
        compact = NamedTuple[]
        positions = Dict{Any,Int}()
        for r in rows
            key = (r.contract.signature, r.doc === nothing ? nothing : r.doc.doc)
            if haskey(positions, key)
                i = positions[key]
                groups = sort!(unique(vcat(isempty(compact[i].objects) ? ["unassigned"] : compact[i].objects,
                    isempty(r.objects) ? ["unassigned"] : r.objects)))
                compact[i] = merge(compact[i], (objects=groups,))
            else
                fallback = r.method === nothing ? r.contract.signature : reflected_signature(r.method)
                push!(compact, merge(r, (short_signature=short_signature(r.contract.signature, fallback),)))
                positions[key] = length(compact)
            end
        end
        rows = compact
        for signature in (isempty(external_package) ? contract_conflicts(rows) : String[])
            push!(gaps, "$label: distinct docstrings document the same signature `$signature`; declaration/method contract precedence is not specified.")
        end
        # `Ref{Any}` keeps every entry the same NamedTuple type; a bare `v` makes the
        # type depend on the function and every helper compile once per entry.
        push!(entries, (value=Ref{Any}(v), label=label, name=string(nameof(v)), location=location,
            objects=belonging, rows=rows, docs=ds, aliases=sort!(unique(exports[v])), istype=istype,
            external_package=external_package))
    end
    paths = Dict{String,Vector{String}}()
    entrypaths = Dict{String,String}()
    # An entry is a NamedTuple whose type depends on the function it documents, so a
    # closure over one entry applied to every entry compiles once per pair of
    # entries (696 x 696): the generation never left this loop (lead, 2026-11-25).
    namecount = Dict{Tuple{String,String},Int}()
    for e in entries
        k = (String(e.location), lowercase(String(e.name)))
        namecount[k] = get(namecount, k, 0) + 1
    end
    for e in entries
        collisions = namecount[(String(e.location), lowercase(String(e.name)))]
        fname = collisions > 1 ? modname(parentmodule(e.value[])) * "." * e.name : e.name
        p = joinpath(out, e.location, filename(fname))
        entrypaths[e.label] = p
        for name in unique(vcat([e.name, e.label], e.aliases))
            push!(get!(paths, name, String[]), p)
        end
    end
    foreach(unique!, values(paths))
    outputfiles = Dict{String,String}()
    sources = Dict{String,Vector{Tuple{Any,String}}}()
    via_sources = Dict{String,Vector{Tuple{Any,String}}}()
    spec_methods = Dict{String,Vector{Any}}()
    spec_targets = Dict{String,NamedTuple{(:page, :anchor),Tuple{String,String}}}()
    # A diagnostic driver may freeze the Markdown inputs while other lanes edit.
    pagecache = spec_pages === nothing ? spec_catalog() : spec_pages
    # Include every real heading, even when no contract points back to it yet.
    # Explicit aliases are added on use; they do not create fictitious sections.
    for (pagepath, page) in pagecache, section in page.sections
        target = (page=pagepath, anchor=section.anchor)
        locator = spec_locator(target)
        spec_targets[locator] = target
        spec_methods[locator] = Any[]
    end
    referencecache = Dict{String,Any}()
    unresolved = String[]
    malformed = String[]
    indexed = NamedTuple[]
    for e in entries
        p = entrypaths[e.label]
        io = IOBuffer()
        print(io, BANNER, "# ", e.label, "\n\n", "Exports: ", join(code.(e.aliases), ", "), "\n\n")
        for r in e.rows
            row = merge(r, (path=p, label=e.label, istype=e.istype, external_package=e.external_package))
            push!(indexed, row)
            println(io, "## ", code(r.contract.signature), "\n")
            if !isempty(e.external_package)
                println(io, "[external: ", e.external_package, "]\n\nThe docstring belongs to `", e.external_package, "`; it is not assessed as a Topology contract.\n")
                r.doc === nothing || println(io, render_doc(r.doc.raw, p, paths, unresolved, e.label; external=true), "\n")
            elseif r.doc === nothing
                println(io, "[no contract]\n")
            else
                println(io, render_doc(r.doc.raw, p, paths, unresolved, e.label), "\n")
                isempty(r.contract.missing) || println(io, "[incomplete: ", join(r.contract.missing, ", "), "]\n")
            end
            for url in r.contract.links
                target = spec_target(url)
                target === nothing && continue
                locator = spec_locator(target)
                resolved = get!(referencecache, locator) do
                    spec_reference(target, pagecache)
                end
                if !isempty(resolved.error)
                    push!(unresolved, indexline(row, joinpath(out, "GAPS.md")) *
                        " — " * code(locator) * ": " * resolved.error)
                    continue
                end
                spec_targets[locator] = target
                push!(get!(spec_methods, locator, Any[]), row)
                isempty(resolved.clarification) || push!(unresolved,
                    indexline(row, joinpath(out, "GAPS.md")) * " — " *
                    code(locator) * ": " * resolved.clarification)
                for key in resolved.citations
                    push!(get!(via_sources, key, Tuple{Any,String}[]), (row, locator))
                end
            end
            refs = Tuple{String,String}[]
            r.doc === nothing || append!(refs, [("function", s) for s in cf_lines(r.doc.raw)])
            for (object, vals) in sort!(collect(types); by=first), t in vals
                any(arg -> mentions(arg, t), r.args) || (e.istype && e.value[] === t) || continue
                tdocs = get!(doccache, t) do
                    documents(t, mods)
                end
                for td in tdocs, s in cf_lines(td.raw)
                    r.doc !== nothing && td.doc === r.doc.doc && continue
                    push!(refs, ("type " * qualified(t), s))
                end
            end
            locs = Tuple{String,Int}[]
            external = String[]
            if r.method !== nothing
                # `Base.updated_methodloc` goes through Revise on the warm server and
                # re-derives every file's signatures; the generation then ran past
                # 10 minutes (lead, 2026-11-25). The loaded location is enough here.
                file, line = String(r.method.file), r.method.line
                sf = source_file(file)
                sf === nothing || push!(locs, (sf, Int(line)))
                sf === nothing && push!(external, external_location(r.method))
            end
            if r.doc !== nothing
                sf = source_file(get(r.doc.doc.data, :path, ""))
                sf === nothing || push!(locs, (sf, Int(get(r.doc.doc.data, :linenumber, 0))))
            end
            for (f, _) in unique(locs), s in file_sources(f)
                push!(refs, ("file " * slash(relpath(f, ROOT)), s))
            end
            unique!(refs)
            inherited = filter(x -> first(x) != "function", refs)
            if !isempty(inherited)
                println(io, "### Inherited sources\n")
                for (scope, s) in inherited
                    println(io, "- **", scope, "**: ", render_doc(s, p, paths, unresolved, e.label))
                end
                println(io)
            end
            println(io, "### Definition\n")
            for (f, line) in unique(locs)
                println(io, "- [", slash(relpath(f, ROOT)), ":", line, "](", link(p, f), "#L", line, ")")
            end
            for locator in external
                println(io, "- ", code(locator))
            end
            isempty(locs) && isempty(external) && println(io, "No loaded definition location is available.")
            println(io)
            for (scope, s) in refs
                m = match(r"^cf:\s*\[\[([^\]#]+)(?:#[^\]]+)?\]\]", s)
                if m === nothing
                    push!(malformed, indexline(row, joinpath(out, "SOURCES.md")) * " — " * scope * ": " * s)
                else
                    push!(get!(sources, m.captures[1], Tuple{Any,String}[]), (row, scope))
                end
            end
        end
        println(io, "## Object indexes\n")
        for key in e.objects
            println(io, "- [", key, "](", link(p, joinpath(out, key, "INDEX.md")), ")")
        end
        outputfiles[p] = String(take!(io))
    end
    objects = sort!(unique(vcat(collect(keys(reg)), ["unassigned"])))
    top = IOBuffer()
    print(top, BANNER, "# API objects\n\n")
    for key in objects
        p = joinpath(out, key, "INDEX.md")
        rs = filter(r -> key in (isempty(r.objects) ? ["unassigned"] : r.objects), indexed)
        sort!(rs; by=r -> (r.label, r.contract.signature))
        name = key == "unassigned" ? "Unassigned public functions" : reg[key]["name"]
        ts = key == "unassigned" ? String[] : reg[key]["types"]
        complete = count(r -> r.contract.status == "complete", rs)
        documented = count(r -> isempty(r.external_package) && r.doc !== nothing, rs)
        external_count = count(r -> !isempty(r.external_package), rs)
        println(top, "- [", name, "](", key, "/INDEX.md) — types: ", isempty(ts) ? "none" : join(code.(ts), ", "),
            " — methods: ", length(rs), " — contracts: ", documented, " (complete: ", complete,
            ") — external: ", external_count)
        io = IOBuffer()
        print(io, BANNER, "# ", name, "\n\nTypes: ", isempty(ts) ? "none" : join(code.(ts), ", "), "\n\n")
        if key != "unassigned"
            for field in ("specs", "conventions")
                println(io, uppercasefirst(field), ": ", join(["[" * basename(t) * "](" *
                    link(p, joinpath(ROOT, t)) * ")" for t in reg[key][field]], ", "), "\n")
            end
        end
        for role in ROLES
            subset = filter(r -> r.contract.role == role, rs)
            isempty(subset) && continue
            println(io, "## ", role, "\n")
            for r in subset
                println(io, indexline(r, p))
            end
            println(io)
        end
        outputfiles[p] = String(take!(io))
    end
    outputfiles[joinpath(out, "INDEX.md")] = String(take!(top))
    p = joinpath(out, "SOURCES.md")
    io = IOBuffer()
    print(io, BANNER, "# Sources\n\n")
    for key in sort!(union(collect(keys(sources)), collect(keys(via_sources))))
        println(io, "## ", key, "\n")
        println(io, "### 直接の出典\n")
        bymethod = Dict{String,Vector{String}}()
        for (r, scope) in get(sources, key, Tuple{Any,String}[])
            push!(get!(bymethod, indexline(r, p), String[]), scope)
        end
        lines = String[]
        for (line, scopes) in bymethod
            inherited = sort!(unique(filter(!=("function"), scopes)))
            push!(lines, line * (isempty(inherited) ? "" : " — inherited: " * join(inherited, "; ")))
        end
        foreach(s -> println(io, s), sort!(unique(lines)))
        println(io)
        println(io, "### 仕様を介した依存\n")
        lines = String[]
        seen = Set{Tuple{Tuple{String,String,String},String}}()
        for (r, locator) in get(via_sources, key, Tuple{Any,String}[])
            identity = (rowkey(r), locator)
            identity in seen && continue
            push!(seen, identity)
            push!(lines, indexline(r, p) * " — via [" * locator * "](" *
                spec_link(p, spec_targets[locator]) * ")")
        end
        foreach(s -> println(io, s), sort!(lines))
        println(io)
    end
    println(io, "## Sources without a registered-key form\n")
    foreach(s -> println(io, s), sort!(unique(malformed)))
    outputfiles[p] = String(take!(io))
    p = joinpath(out, "SPECS.md")
    io = IOBuffer()
    print(io, BANNER, "# Specification and convention references\n\n")
    println(io, "A heading without method rows has no contract links to that anchor. Page-only links and paragraph anchors carry no source attribution.\n")
    for locator in sort!(collect(keys(spec_methods)); by=k ->
            (spec_targets[k].page, spec_targets[k].anchor))
        target = spec_targets[locator]
        println(io, "## [", locator, "](", spec_link(p, target), ") — ",
            oneline(spec_title(target, pagecache)), "\n")
        lines = String[]
        seen = Set{Tuple{String,String,String}}()
        for r in spec_methods[locator]
            identity = rowkey(r)
            identity in seen && continue
            push!(seen, identity)
            push!(lines, indexline(r, p))
        end
        foreach(s -> println(io, s), sort!(lines))
        println(io)
    end
    outputfiles[p] = String(take!(io))
    p = joinpath(out, "GAPS.md")
    io = IOBuffer()
    print(io, BANNER, "# Contract gaps\n\n")
    # §4.7 indexes exported types as constructor functions. Library-owned
    # callables form the contract partition; external re-exports form a fourth class.
    functions = filter(e -> isempty(e.external_package), entries)
    external_entries = filter(e -> !isempty(e.external_package), entries)
    functionstatus(e) = all(r -> r.contract.status == "no contract", e.rows) ? "no contract" :
        any(r -> r.contract.status != "complete", e.rows) ? "incomplete" : "complete"
    counts = Dict(s => count(e -> functionstatus(e) == s, functions) for s in ("no contract", "incomplete", "complete"))
    evidence_counts = Dict(s => 0 for s in GUARANTEE_STATUSES)
    missing_evidence = 0
    unsettled = NamedTuple{(:label, :signature, :number, :status, :annotation),Tuple{String,String,Int,String,String}}[]
    # Count a numbered item once per callable and docstring, not once per optional
    # method or object index. These records carry strings, never callable types.
    for e in functions
        seen = Base.IdSet{Any}()
        for r in e.rows
            r.doc === nothing && continue
            r.doc.doc in seen && continue
            push!(seen, r.doc.doc)
            for g in r.contract.guarantees
                if isempty(g.status)
                    missing_evidence += 1
                else
                    evidence_counts[g.status] += 1
                    if g.status in ("unverified", "open")
                        push!(unsettled, (label=e.label, signature=r.contract.signature,
                            number=g.number, status=g.status, annotation=g.annotation))
                    end
                end
            end
        end
    end
    println(io, "Public functions indexed (unique callable identities, including constructors): ", length(entries))
    println(io, "\nLibrary-owned functions assessed: ", length(functions))
    println(io, "\nExternal re-exported bindings: ", length(external_entries))
    println(io, "\nNo contract: ", counts["no contract"], "\n\nIncomplete: ", counts["incomplete"], "\n\nComplete: ", counts["complete"])
    println(io, "\nConstructor functions indexed (included above): ", count(e -> e.istype, entries))
    println(io, "\nMethod rows (before repetition across object indexes): ", length(indexed))
    println(io, "\nUnassigned public functions: ", count(e -> !e.istype && e.location == "unassigned", entries))
    println(io, "\nUnregistered or multiply registered exported types: ", length(unregistered), "\n")
    println(io, "Exports not indexed: ", length(unique(omitted)), "\n")
    println(io, "Items requiring specification clarification: ", length(unique(gaps)), "\n")
    println(io, "Unresolved references: ", length(unique(unresolved)), "\n")
    println(io, "Guarantees by evidence status (once per callable/docstring, before repetition across methods or indexes):\n")
    for status in GUARANTEE_STATUSES
        println(io, "- ", status, ": ", evidence_counts[status])
    end
    println(io, "- missing or invalid status: ", missing_evidence, "\n")
    println(io, "A library-owned function has no contract when all its rows lack docstrings; it is complete when every row is complete, and incomplete otherwise. Constructor functions participate in these counts; aliases share one identity. External re-exports are excluded from all three contract counts and from guarantee counts. The three counts plus external bindings equal the indexed total.\n")
    println(io, "Object-index contract counts include incomplete docstrings; complete counts are shown separately.\n")
    println(io, "An absent return annotation is displayed as `-> ?`; a docstring lacking it is incomplete.\n")
    for status in ("no contract", "incomplete", "complete")
        println(io, "## ", uppercasefirst(status), "\n")
        for e in functions
            functionstatus(e) == status || continue
            misses = sort!(unique(vcat([r.contract.missing for r in e.rows]...)))
            println(io, "- [", e.label, "](", link(p, entrypaths[e.label]), ")", isempty(misses) ? "" : " — " * join(misses, ", "))
        end
        println(io)
    end
    for status in ("unverified", "open")
        println(io, "## Guarantees: ", status, "\n")
        for g in sort!(filter(g -> g.status == status, unsettled); by=g -> (g.label, g.signature, g.number))
            println(io, "- [", g.label, "](", link(p, entrypaths[g.label]), ") — ",
                code(g.signature), " — Guarantee ", g.number, " — [", g.annotation, "]")
        end
        println(io)
    end
    println(io, "## 外部パッケージから再exportされた束縛\n")
    for e in external_entries
        println(io, "- [", e.label, "](", link(p, entrypaths[e.label]), ") [external: ", e.external_package, "]")
    end
    println(io, "\n## どの対象にも属さない公開関数\n")
    for e in entries
        !e.istype && e.location == "unassigned" && println(io, "- [", e.label, "](", link(p, entrypaths[e.label]), ")")
    end
    println(io, "\n## どの対象にも属さない export された型\n")
    foreach(s -> println(io, "- ", s), sort!(unregistered))
    println(io, "\n## 索引に載せない export\n")
    foreach(s -> println(io, "- ", s), sort!(unique(omitted)))
    println(io, "\n## 仕様が置き場所を定めていないもの\n")
    foreach(s -> println(io, "- ", s), sort!(unique(gaps)))
    println(io, "\n## 解決できない参照\n")
    foreach(s -> println(io, startswith(s, "- ") ? s : "- " * s), sort!(unique(unresolved)))
    outputfiles[p] = String(take!(io))

    # Verify all destinations before writing; delete stale files only after all
    # new content has been written and verified byte for byte.
    for path in keys(outputfiles)
        rel = relpath(normpath(path), out)
        (rel == ".." || startswith(slash(rel), "../") || isabspath(rel)) && error("Output escapes docs/api")
    end
    for path in sort!(collect(keys(outputfiles)))
        mkpath(dirname(path))
        write(path, outputfiles[path])
    end
    problems = [p for (p, content) in outputfiles if read(p, String) != content]
    isempty(problems) || error("Output verification failed; stale files retained: $(join(problems, ", "))")
    for (dir, _, files) in walkdir(out)
        for file in files
            path = joinpath(dir, file)
            haskey(outputfiles, path) || rm(path)
        end
    end
    for (dir, _, _) in walkdir(out; topdown=false)
        dir == out && continue
        isempty(readdir(dir)) && rm(dir)
    end
    println("API generated: ", length(entries), " functions; no contract=", counts["no contract"],
        ", incomplete=", counts["incomplete"], ", complete=", counts["complete"],
        ", external=", length(external_entries), "; placement gaps=", length(unique(gaps)))
    nothing
end
